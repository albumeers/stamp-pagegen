# ISO 639-1 Language Code to English Name Mapping
ISO_639_1_LANGUAGES: Dict[str, str] = {
    "de": "German",
    "fr": "French",
    "es": "Spanish",
    "it": "Italian",
    "nl": "Dutch",
    "pt": "Portuguese",
    "ru": "Russian",
    "pl": "Polish",
    "cs": "Czech",
    "hu": "Hungarian",
    "sv": "Swedish",
    "da": "Danish",
    "no": "Norwegian",
    "fi": "Finnish",
    "el": "Greek",
    "tr": "Turkish",
    "ja": "Japanese",
    "zh": "Chinese",
    "en": "English",
}

DEFAULT_OLLAMA_URL = "http://localhost:11434"
DEFAULT_MODEL = "codegemma:7b"


def get_language_name(code: str) -> str:
    """Returns the full human-readable language name for an ISO 639-1 code."""
    normalized = code.strip().lower()
    return ISO_639_1_LANGUAGES.get(normalized, f"Language ({normalized})")


def check_ollama_available(ollama_url: str = DEFAULT_OLLAMA_URL, timeout: float = 3.0) -> bool:
    """Checks if the local Ollama daemon is reachable."""
    try:
        url = urllib.parse.urljoin(ollama_url, "/api/tags")
        req = urllib.request.Request(url, headers={"User-Agent": "translate-articles/1.0"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status == 200
    except Exception:
        return False


def clean_translated_text(translated: str, original: str) -> str:
    """
    Cleans up any conversational preamble, prompt echoes, leaked system prompts,
    or markdown headers from LLM translation output.
    """
    if not translated:
        return original
    text = translated.strip()

    # 1. Strip surrounding quotes if the model wrapped the response
    if (text.startswith('"') and text.endswith('"')) or (text.startswith("'") and text.endswith("'")):
        text = text[1:-1].strip()

    # 2. Detect and discard conversational LLM chatter/refusals
    # E.g. "Dear Carolinus, I am ready to translate...", "Thank you for your message..."
    if re.search(r"^(?:Dear\s+[A-Za-z0-9_ -]+,?\s+)?(?:Thank you for your message\b|I\s+am\s+ready\s+to\s+translate\b|Please\s+(?:share|provide)\s+the\s+text\b)", text, re.IGNORECASE):
        return original
    if re.search(r"^Carolinus\s+is\s+an\s+expert\s+philatelic\s+translator", text, re.IGNORECASE):
        return original

    # 3. Strip any leaked system prompt text or instructions
    leak_patterns = [
        r"^.*?(?:You are an expert translator|You are a professional translator|You are a translator).*?(?:\n|$)",
        r"^.*?(?:Key philatelic terminology|Accurately translate the provided text).*?(?:\n|$)",
        r"^.*?(?:Return ONLY the direct translation|Instructions:\s*1\.).*?(?:\n|$)",
        r"^.*?(?:Key philatelic terminology guidelines:.*?perforation['\"]?\s*)",
    ]
    for pat in leak_patterns:
        text = re.sub(pat, "", text, flags=re.IGNORECASE | re.DOTALL).strip()

    # 4. Strip preamble markers (e.g. "**Direct Translation:**", "Translation:", "Here is the translation:")
    preamble_patterns = [
        r"^(?:\*{1,3}|#{1,6})?\s*(?:Direct\s+)?(?:English\s+)?Translation(?:\s*(?:from|into|of)[^\n:]*)?[:\*\s-]+\s*",
        r"^(?:(?:Here|As\s+requested,?\s+here)\s+is\s+the\s+(?:direct\s+)?translation\s*:\s*)",
        r"^(?:The\s+provided\s+text\s+(?:translates\s+as\s+follows|can\s+be\s+translated\s+as)\s*:\s*)",
    ]
    for pat in preamble_patterns:
        text = re.sub(pat, "", text, flags=re.IGNORECASE).strip()

    # 5. Strip surrounding quotes again if they were enclosing the translation after preamble
    if (text.startswith('"') and text.endswith('"')) or (text.startswith("'") and text.endswith("'")):
        text = text[1:-1].strip()

    return text if text else original


def query_ollama_translation(
    text: str,
    source_lang: str = "de",
    target_lang: str = "en",
    model: str = DEFAULT_MODEL,
    ollama_url: str = DEFAULT_OLLAMA_URL,
    timeout: int = 60,
    max_retries: int = 2,
) -> str:
    """
    Translates text from source_lang to target_lang using Ollama /api/chat.
    Specialized for philatelic and historical collector terminology.
    """
    clean_text = text.strip()
    if not clean_text:
        return text

    source_lang_name = get_language_name(source_lang)
    target_lang_name = get_language_name(target_lang)

    system_prompt = (
        f"You are a professional translator specializing in philatelic (stamp collecting), "
        f"postal history, and auction terminology.\n"
        f"Translate the provided text directly and accurately from {source_lang_name} into fluent, natural {target_lang_name}.\n"
        f"Output ONLY the direct translation without explanation, preamble, or conversational remarks."
    )

    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": f"Text to translate:\n{clean_text}"},
        ],
        "stream": False,
        "options": {
            "temperature": 0.1,
        },
    }

    data = json.dumps(payload).encode("utf-8")
    api_endpoint = urllib.parse.urljoin(ollama_url, "/api/chat")

    for attempt in range(max_retries + 1):
        try:
            req = urllib.request.Request(
                api_endpoint,
                data=data,
                headers={"Content-Type": "application/json", "User-Agent": "translate-articles/1.0"},
            )
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                res_json = json.loads(resp.read().decode("utf-8"))
                translated = res_json.get("message", {}).get("content", "").strip()
                cleaned = clean_translated_text(translated, clean_text)
                return cleaned if cleaned else text
        except Exception as e:
            if attempt < max_retries:
                time.sleep(1.0)
            else:
                print(f"Warning: Ollama translation failed ({e}). Keeping original text.")
                return text

    return text


def update_image_links_for_subfolder(
    html_content: str,
    images_dir: Optional[str] = None,
) -> str:
    """
    Updates image links in HTML so that documents residing in an 'en/' subfolder
    correctly reference images in the parent folder's 'images/' directory.

    Key operations:
    1. Removes any <base href="..."> tags from <head>. Headless Chrome's print-to-pdf
       engine evaluates relative links (like '../images/...') against <base href> if present,
       which would cause relative paths to be converted into website URLs (e.g. https://philaforum.com/...)
       instead of resolving to the local file system.
    2. Converts relative images/ and ./images/ paths to ../images/ for both href and src.
    3. Converts absolute file:///.../images/<filename> paths to ../images/<filename>.
    4. If images_dir is provided, maps any attachment URLs or known image filenames to ../images/<filename>.
    """
    # 1. Strip <base href="..."> so relative paths resolve against the local file system
    updated = re.sub(r"<base\b[^>]*>", "", html_content, flags=re.IGNORECASE)

    # 2. Update relative images/ paths
    updated = re.sub(
        r'(\b(?:href|src)=["\'])(?:\.\/)?images\/',
        r"\g<1>../images/",
        updated,
        flags=re.IGNORECASE,
    )

    # 3. Update absolute file:/// paths ending in /images/<filename> to portable relative ../images/<filename>
    def replace_file_url(m):
        attr = m.group(1)
        raw_fname = m.group(2)
        quote = m.group(3)
        clean_fname = transliterate_german(raw_fname)
        clean_fname = re.sub(r'[\\/*?:"<>|%]', "", clean_fname).strip()
        return f"{attr}../images/{clean_fname}{quote}"

    updated = re.sub(
        r'(\b(?:href|src)=["\'])file:\/\/\/[^"\'<>]*\/images\/([^"\'<>]+)(["\'])',
        replace_file_url,
        updated,
        flags=re.IGNORECASE,
    )

    # 4. If images_dir exists, map any attachment URLs that match files in images_dir
    if images_dir and os.path.isdir(images_dir):
        # Index images in images_dir by attachment ID prefix and by filename
        id_to_file: Dict[str, str] = {}
        for fname in os.listdir(images_dir):
            id_to_file[fname.lower()] = fname
            m_id = re.match(r"^(\d+)-", fname)
            if m_id:
                id_to_file[m_id.group(1)] = fname

        def replace_attachment_url(m):
            attr_prefix = m.group(1)
            full_url = m.group(2)
            quote = m.group(3)
            att_m = re.search(r"/attachment/(\d+)", full_url, re.IGNORECASE)
            if att_m:
                att_id = att_m.group(1)
                if att_id in id_to_file:
                    return f"{attr_prefix}../images/{id_to_file[att_id]}{quote}"
            for fname_key, real_fname in id_to_file.items():
                if full_url.lower().endswith(fname_key):
                    return f"{attr_prefix}../images/{real_fname}{quote}"
            return m.group(0)

        updated = re.sub(
            r'(\b(?:href|src)=["\'])([^"\']*\/attachment\/\d+[^"\']*)(["\'])',
            replace_attachment_url,
            updated,
            flags=re.IGNORECASE,
        )

    return updated


def ensure_image_scaling_styles(html_content: str) -> str:
    """
    Ensures CSS overrides for attachment cards and images are present in the HTML document,
    preventing WoltLab CSS Grid from shrinking attachment preview images to 100px thumbnail width.
    """
    if ".messageAttachmentList" in html_content and ".attachmentImagePreview" in html_content:
        # Rules already present in stylesheet
        return html_content

    scaling_css = """
<style>
@media print, screen {
    .messageAttachmentList {
        display: block !important;
        grid-template-columns: none !important;
    }
    .messageAttachment {
        display: block !important;
        grid-template-columns: none !important;
        grid-template-areas: none !important;
        max-width: 100% !important;
        width: auto !important;
    }
    .attachmentImagePreview {
        display: block !important;
        width: 100% !important;
        max-width: 100% !important;
        text-align: center !important;
        margin-bottom: 12px !important;
    }
    .embeddedImage,
    .attachmentThumbnail img,
    .attachmentImagePreview img,
    .messageAttachment img,
    .messageBody img,
    .messageText img {
        max-width: 100% !important;
        max-height: 850px !important;
        width: auto !important;
        height: auto !important;
        display: inline-block !important;
        object-fit: contain !important;
    }
}
</style>
"""
    if "</head>" in html_content:
        return html_content.replace("</head>", f"{scaling_css}\n</head>", 1)
    elif "<body" in html_content:
        return re.sub(r"(<body\b[^>]*>)", rf"\1\n{scaling_css}", html_content, count=1, flags=re.IGNORECASE)
    else:
        return f"{scaling_css}\n{html_content}"


def extract_thread_url_from_pdf(pdf_path: str) -> Optional[str]:
    """
    Extracts the Philaforum forum thread URL from PDF annotations or text streams.
    First uses pypdf to inspect annotation URI actions.
    Falls back to regex scanning with PDF string unescaping (handling octal escapes like \\072\\057 and hex literals).
    """
    if not os.path.isfile(pdf_path):
        return None

    # 1. Primary: Use pypdf to inspect annotation URI actions
    try:
        import pypdf
        reader = pypdf.PdfReader(pdf_path)
        for page in reader.pages:
            annots = page.get("/Annots")
            if not annots:
                continue
            for annot in annots:
                try:
                    obj = annot.get_object() if hasattr(annot, "get_object") else annot
                    if not isinstance(obj, dict):
                        continue
                    action = obj.get("/A")
                    if hasattr(action, "get_object"):
                        action = action.get_object()
                    if isinstance(action, dict) and action.get("/S") == "/URI":
                        uri = action.get("/URI", "")
                        if "/forum/thread/" in uri:
                            clean = uri.split("?")[0].split("#")[0].rstrip("/") + "/"
                            if re.search(r"/thread/\d+-[^/]+/", clean):
                                return clean
                except Exception:
                    continue
    except Exception:
        pass

    # 2. Secondary: Regex scanning with PDF octal and escape decoding
    try:
        with open(pdf_path, "rb") as f:
            pdf_bytes = f.read()

        # Match /URI (string)
        raw_uris = re.findall(rb"/URI\s*\((.*?)\)", pdf_bytes, re.DOTALL)
        for raw in raw_uris:
            # Decode octal escapes: \ddd
            unescaped = re.sub(rb"\\([0-7]{1,3})", lambda m: bytes([int(m.group(1), 8)]), raw)
            unescaped = (
                unescaped.replace(rb"\\n", b"\n")
                .replace(rb"\\r", b"\r")
                .replace(rb"\\t", b"\t")
                .replace(rb"\\b", b"\b")
                .replace(rb"\\f", b"\f")
                .replace(rb"\\(", b"(")
                .replace(rb"\\)", b")")
                .replace(rb"\\\\", b"\\")
            )
            decoded = unescaped.decode("utf-8", errors="ignore")
            if "/forum/thread/" in decoded:
                clean = decoded.split("?")[0].split("#")[0].rstrip("/") + "/"
                if re.search(r"/thread/\d+-[^/]+/", clean):
                    return clean

        # Also match /URI <hex>
        hex_uris = re.findall(rb"/URI\s*<([0-9a-fA-F]+)>", pdf_bytes)
        for h in hex_uris:
            try:
                decoded = bytes.fromhex(h.decode("ascii")).decode("utf-8", errors="ignore")
                if "/forum/thread/" in decoded:
                    clean = decoded.split("?")[0].split("#")[0].rstrip("/") + "/"
                    if re.search(r"/thread/\d+-[^/]+/", clean):
                        return clean
            except Exception:
                continue
    except Exception as e:
        print(f"Warning: Could not extract thread URL from {pdf_path}: {e}")

    return None


def extract_text_from_pdf_fallback(pdf_path: str) -> str:
    """
    Fallback PDF text extractor for Chrome/Skia-generated PDFs.
    Parses font ToUnicode CMaps and content streams directly in pure Python without extra dependencies.
    """
    try:
        with open(pdf_path, "rb") as f:
            data = f.read()

        def get_stream(obj_id: int) -> bytes:
            pattern = rb"\b" + str(obj_id).encode() + rb"\s+0\s+obj\s*<<(?:(?!>>).)*>>\s*stream[\r\n]+(.*?)[\r\n]+endstream"
            m = re.search(pattern, data, re.DOTALL)
            if m:
                try:
                    return zlib.decompress(m.group(1))
                except Exception:
                    return m.group(1)
            return b""

        def parse_cmap(cmap_bytes: bytes) -> Dict[int, str]:
            char_map = {}
            decomp = cmap_bytes.decode("latin1", "ignore")
            for bfchar_block in re.findall(r"(\d+)\s+beginbfchar(.*?)endbfchar", decomp, re.DOTALL):
                pairs = re.findall(r"<([0-9a-fA-F]+)>\s+<([0-9a-fA-F]+)>", bfchar_block[1])
                for src_hex, dst_hex in pairs:
                    char_map[int(src_hex, 16)] = chr(int(dst_hex, 16))
            for bfrange_block in re.findall(r"(\d+)\s+beginbfrange(.*?)endbfrange", decomp, re.DOTALL):
                ranges = re.findall(r"<([0-9a-fA-F]+)>\s+<([0-9a-fA-F]+)>\s+<([0-9a-fA-F]+)>", bfrange_block[1])
                for start_hex, end_hex, dst_hex in ranges:
                    start_val = int(start_hex, 16)
                    end_val = int(end_hex, 16)
                    dst_start = int(dst_hex, 16)
                    for offset in range(end_val - start_val + 1):
                        char_map[start_val + offset] = chr(dst_start + offset)
            return char_map

        # Map fonts to their ToUnicode CMaps
        font_cmaps = {}
        for m in re.finditer(rb"/Type\s*/Font\s*/Subtype\s*/Type0.*?/ToUnicode\s+(\d+)\s+0\s+R", data, re.DOTALL):
            tu_id = int(m.group(1))
            font_cmaps[tu_id] = parse_cmap(get_stream(tu_id))

        font_id_map = {}
        for m in re.finditer(rb"/F(\d+)\s+(\d+)\s+0\s+R", data):
            f_num = "F" + m.group(1).decode()
            f_obj = int(m.group(2))
            tu_m = re.search(rb"\b" + str(f_obj).encode() + rb"\s+0\s+obj.*?/ToUnicode\s+(\d+)\s+0\s+R", data, re.DOTALL)
            if tu_m:
                tu_id = int(tu_m.group(1))
                if tu_id in font_cmaps:
                    font_id_map[f_num] = font_cmaps[tu_id]

        # Extract text from content streams
        pages = re.findall(rb"/Type\s*/Page\b.*?/Contents\s+(\d+)\s+0\s+R", data, re.DOTALL)
        extracted_lines = []

        for p_cid in pages:
            cstream = get_stream(int(p_cid)).decode("latin1", "ignore")
            current_font = None
            cur_line = []
            for token in re.finditer(r"/F\d+\s+[\d.]+\s+Tf|<[0-9a-fA-F]+>\s*Tj|ET", cstream):
                t_str = token.group(0)
                if t_str.startswith("/F") and "Tf" in t_str:
                    current_font = t_str.split()[0].lstrip("/")
                elif t_str.startswith("<") and "Tj" in t_str:
                    hex_str = re.search(r"<([0-9a-fA-F]+)>", t_str).group(1)
                    cmap = font_id_map.get(current_font, {})
                    decoded_chars = []
                    for i in range(0, len(hex_str), 4):
                        cid = int(hex_str[i : i + 4], 16)
                        decoded_chars.append(cmap.get(cid, " "))
                    cur_line.append("".join(decoded_chars))
                elif t_str == "ET":
                    if cur_line:
                        extracted_lines.append(" ".join(cur_line).strip())
                        cur_line = []

        return "\n".join(line for line in extracted_lines if line)
    except Exception as e:
        print(f"Warning: Fallback text extraction failed: {e}")
        return ""


def translate_post_text(
    inner_html: str,
    source_lang: str,
    target_lang: str,
    model: str,
    ollama_url: str,
) -> str:
    """
    Translates the messageText content of a post, preserving all embedded images,
    attachment cards, and blockquotes intact.
    """
    # 1. Translate quote boxes separately if present
    def translate_quote_block(m):
        full_quote = m.group(0)
        quote_attrs = m.group(1)
        quote_inner = m.group(2)
        # Translate quote text
        clean_quote_text = html.unescape(re.sub(r"<[^>]+>", " ", quote_inner).strip())
        if clean_quote_text:
            trans_quote = query_ollama_translation(
                clean_quote_text,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
            )
            return f'<blockquote{quote_attrs}><p>{html.escape(trans_quote)}</p></blockquote>'
        return full_quote

    processed = re.sub(
        r"<blockquote\b([^>]*)>(.*?)</blockquote>",
        translate_quote_block,
        inner_html,
        flags=re.DOTALL | re.IGNORECASE,
    )

    # 2. Extract and protect any image containers (<div class="attachmentImagePreview">, <a class="embeddedImageLink">, <img>)
    placeholders: Dict[str, str] = {}
    ph_counter = 0

    def protect_images(m):
        nonlocal ph_counter
        key = f"___IMG_PLACEHOLDER_{ph_counter}___"
        placeholders[key] = m.group(0)
        ph_counter += 1
        return f"\n{key}\n"

    # Protect image preview divs
    processed = re.sub(
        r'<div\b[^>]*class=["\'][^"\']*attachmentImagePreview[^"\']*["\'][^>]*>.*?</div>',
        protect_images,
        processed,
        flags=re.DOTALL | re.IGNORECASE,
    )

    # Protect embedded image anchors
    processed = re.sub(
        r'<a\b[^>]*class=["\'][^"\']*embeddedImageLink[^"\']*["\'][^>]*>.*?</a>',
        protect_images,
        processed,
        flags=re.DOTALL | re.IGNORECASE,
    )

    # Protect attachment file cards
    processed = re.sub(
        r'<a\b[^>]*class=["\'][^"\']*messageAttachment[^"\']*["\'][^>]*>.*?</a>',
        protect_images,
        processed,
        flags=re.DOTALL | re.IGNORECASE,
    )

    # Protect any remaining <img> tags
    processed = re.sub(
        r"<img\b[^>]*>",
        protect_images,
        processed,
        flags=re.IGNORECASE,
    )

    # 3. Translate paragraphs / text lines
    # Split by <p> tags or lines
    p_pattern = re.compile(r"<p\b[^>]*>(.*?)</p>", re.DOTALL | re.IGNORECASE)

    if p_pattern.search(processed):
        def translate_p(m):
            p_content = m.group(1).strip()
            # If paragraph only contains a placeholder, preserve it
            if re.match(r"^___IMG_PLACEHOLDER_\d+___$", p_content):
                return m.group(0)
            clean_text = html.unescape(re.sub(r"<[^>]+>", " ", p_content).strip())
            if not clean_text:
                return m.group(0)
            trans_text = query_ollama_translation(
                clean_text,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
            )
            return f"<p>{html.escape(trans_text)}</p>"

        translated_body = p_pattern.sub(translate_p, processed)
    else:
        # Fallback for plain text posts with <br>
        clean_text = html.unescape(re.sub(r"<br\s*/?>", "\n", processed))
        clean_text = re.sub(r"<[^>]+>", " ", clean_text).strip()
        if clean_text:
            trans_text = query_ollama_translation(
                clean_text,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
            )
            translated_body = "".join(f"<p>{html.escape(line)}</p>" for line in trans_text.splitlines() if line.strip())
        else:
            translated_body = processed

    # 4. Restore protected image containers
    for key, original_tag in placeholders.items():
        translated_body = translated_body.replace(key, original_tag)

    return translated_body


def translate_thread_html(
    html_content: str,
    source_lang: str = "de",
    target_lang: str = "en",
    model: str = DEFAULT_MODEL,
    ollama_url: str = DEFAULT_OLLAMA_URL,
    images_dir: Optional[str] = None,
) -> Tuple[str, str]:
    """
    Translates thread title and post message texts in the sanitized HTML document,
    updating image links from 'images/' to '../images/' so that output in 'en/' subfolder
    correctly resolves assets. Returns (translated_html, translated_title).
    """
    # 1. Update image links for subfolder depth and strip <base href>
    html_content = update_image_links_for_subfolder(html_content, images_dir=images_dir)

    # 1b. Ensure attachment image scaling CSS styles are present
    html_content = ensure_image_scaling_styles(html_content)

    # 2. Translate thread title
    translated_title = "Translated Thread"
    title_m = re.search(r'<h1[^>]*class="[^"]*contentTitle[^"]*"[^>]*>(.*?)</h1>', html_content, re.DOTALL | re.IGNORECASE)
    if title_m:
        raw_title = html.unescape(re.sub(r"<[^>]+>", "", title_m.group(1)).strip())
        if raw_title:
            print(f"  Translating title: '{raw_title}'...")
            translated_title = query_ollama_translation(
                raw_title,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
            )
            print(f"  -> '{translated_title}'")
            # Replace contentTitle
            html_content = (
                html_content[: title_m.start(1)]
                + html.escape(translated_title)
                + html_content[title_m.end(1) :]
            )

    # Update document <title>
    html_content = re.sub(
        r"<title\b[^>]*>(.*?)</title>",
        rf"<title>{html.escape(translated_title)} ({target_lang.upper()})</title>",
        html_content,
        count=1,
        flags=re.IGNORECASE,
    )

    # 3. Translate each post's messageText
    msg_pattern = re.compile(
        r'(<div\b[^>]*class="[^"]*messageText[^"]*"[^>]*>)(.*?)(</div>\s*</div>)',
        re.DOTALL | re.IGNORECASE,
    )

    matches = list(msg_pattern.finditer(html_content))
    print(f"  Translating {len(matches)} post(s)...")

    # Replace from back to front to preserve string indices
    for idx, m in enumerate(reversed(matches)):
        post_idx = len(matches) - idx
        open_tag = m.group(1)
        inner_body = m.group(2)
        close_tag = m.group(3)

        translated_inner = translate_post_text(
            inner_body,
            source_lang=source_lang,
            target_lang=target_lang,
            model=model,
            ollama_url=ollama_url,
        )

        html_content = (
            html_content[: m.start()]
            + open_tag
            + translated_inner
            + close_tag
            + html_content[m.end() :]
        )

    return html_content, translated_title


def translate_single_pdf(
    pdf_path: str,
    output_dir: str,
    browser_path: str,
    source_lang: str = "de",
    target_lang: str = "en",
    model: str = DEFAULT_MODEL,
    ollama_url: str = DEFAULT_OLLAMA_URL,
    force: bool = False,
    save_text: bool = False,
    render_timeout: Optional[int] = None,
) -> Optional[str]:
    """
    Translates a single PDF article and writes the English PDF into output_dir ('en/').
    Returns the path of the generated PDF on success, or None on failure.
    """
    pdf_basename = os.path.basename(pdf_path)
    target_pdf_path = os.path.join(output_dir, pdf_basename)

    print(f"\n========================================================")
    print(f"Processing: {pdf_basename}")
    print(f"Source: {pdf_path}")
    print(f"Target: {target_pdf_path}")
    print(f"Language: {get_language_name(source_lang)} ({source_lang}) -> {get_language_name(target_lang)} ({target_lang})")
    print(f"Model: {model} @ {ollama_url}")

    if os.path.isfile(target_pdf_path) and os.path.getsize(target_pdf_path) > 0 and not force:
        print(f"  [SKIPPED] Target file already exists. Use --force to re-translate.")
        return target_pdf_path

    # Step 1: Extract thread URL from PDF
    thread_url = extract_thread_url_from_pdf(pdf_path)
    translated_html: Optional[str] = None
    translated_title: Optional[str] = None

    if thread_url:
        print(f"  Found online thread URL: {thread_url}")
        try:
            # Fetch base page 1
            html_p1 = fetch_url(thread_url)
            total_pages = extract_pagination_count(html_p1)

            additional_html = []
            for p in range(2, total_pages + 1):
                page_url = f"{thread_url}?pageNo={p}"
                print(f"  Fetching page {p}/{total_pages}: {page_url}")
                additional_html.append(fetch_url(page_url))

            combined_html = combine_thread_pages(html_p1, additional_html) if additional_html else html_p1
            # Locate images_dir (checks current folder or parent folder for language subfolder layout)
            input_dir = os.path.dirname(os.path.abspath(pdf_path))
            if os.path.isdir(os.path.join(input_dir, "images")):
                images_dir = os.path.join(input_dir, "images")
            elif os.path.isdir(os.path.join(os.path.dirname(input_dir), "images")):
                images_dir = os.path.join(os.path.dirname(input_dir), "images")
            else:
                images_dir = os.path.join(input_dir, "images")

            sanitized_html = sanitize_thread_html(combined_html, base_url=thread_url, images_dir=images_dir)
            translated_html, translated_title = translate_thread_html(
                sanitized_html,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
                images_dir=images_dir,
            )
        except Exception as e:
            print(f"  Warning: Online thread retrieval failed ({e}). Attempting offline fallback.")
            translated_html = None

    # Step 2: Offline fallback if thread URL extraction or network failed
    if not translated_html:
        print(f"  Extracting text from PDF streams (offline fallback)...")
        extracted_text = extract_text_from_pdf_fallback(pdf_path)
        if not extracted_text:
            print(f"  [FAILED] Could not extract text from {pdf_basename}.")
            return None

        clean_title = os.path.splitext(pdf_basename)[0].replace("-", " ")
        translated_title = query_ollama_translation(
            clean_title,
            source_lang=source_lang,
            target_lang=target_lang,
            model=model,
            ollama_url=ollama_url,
        )
        print(f"  Translated title: '{translated_title}'")

        paragraphs = [p.strip() for p in extracted_text.split("\n\n") if p.strip()]
        translated_paragraphs = []
        for p in paragraphs:
            trans_p = query_ollama_translation(
                p,
                source_lang=source_lang,
                target_lang=target_lang,
                model=model,
                ollama_url=ollama_url,
            )
            translated_paragraphs.append(trans_p)

        # Build clean fallback HTML styled like WoltLab thread
        body_html = "".join(f"<p>{html.escape(tp)}</p>" for tp in translated_paragraphs)
        translated_html = f"""<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>{html.escape(translated_title)}</title>
<style>
body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Arial, sans-serif; margin: 30px; color: #2e353b; line-height: 1.6; }}
h1 {{ font-size: 24px; color: #1e3a8a; border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; }}
.post {{ border: 1px solid #cbd5e1; border-radius: 6px; padding: 20px; margin-bottom: 20px; background: #fff; }}
.meta {{ font-size: 13px; color: #64748b; margin-bottom: 12px; }}
p {{ margin-bottom: 1em; }}
img {{ max-width: 100% !important; max-height: 850px !important; height: auto !important; object-fit: contain !important; display: block; margin: 10px auto; }}
</style>
</head>
<body>
<h1>{html.escape(translated_title)}</h1>
<div class="meta">Translated from {get_language_name(source_lang)} to {get_language_name(target_lang)} via {model}</div>
<div class="post">{body_html}</div>
</body>
</html>"""

    # Optional: Save text translation in 'text' subfolder (e.g. en/text/<filename>.txt)
    if save_text:
        text_dir = os.path.join(output_dir, "text")
        os.makedirs(text_dir, exist_ok=True)
        text_basename = os.path.splitext(os.path.basename(target_pdf_path))[0] + ".txt"
        text_path = os.path.join(text_dir, text_basename)
        try:
            with open(text_path, "w", encoding="utf-8") as tf:
                # Strip style and script blocks first, then remaining HTML tags
                plain = re.sub(r"<(style|script)\b[^>]*>.*?</\1>", " ", translated_html, flags=re.DOTALL | re.IGNORECASE)
                plain = re.sub(r"<[^>]+>", " ", plain)
                plain = html.unescape(re.sub(r"\s+", " ", plain)).strip()
                tf.write(f"=== {translated_title} ===\n\n{plain}\n")
            print(f"  Saved text translation: {text_path}")
        except Exception as e:
            print(f"  Warning: Could not save text file {text_path}: {e}")

    # Step 3: Render English PDF with headless Chrome
    print(f"  Rendering English PDF: {os.path.basename(target_pdf_path)}...")
    # Critical: Set temp_dir to output_dir ('.../en') so relative links like '../images/...' resolve correctly!
    success = render_html_to_pdf(
        html_content=translated_html,
        output_pdf_path=target_pdf_path,
        browser_path=browser_path,
        temp_dir=output_dir,
        timeout=render_timeout,
    )

    if success:
        file_size_kb = os.path.getsize(target_pdf_path) // 1024 if os.path.isfile(target_pdf_path) else 0
        print(f"  [SUCCESS] Created {target_pdf_path} ({file_size_kb} KB)")
        return target_pdf_path
    else:
        print(f"  [FAILED] Could not render {os.path.basename(target_pdf_path)}")
        return None


def parse_arguments(argv: Optional[List[str]] = None) -> argparse.Namespace:
    """Parses command-line arguments for translate-articles.py."""
    parser = argparse.ArgumentParser(
        description="Translate German/foreign stamp forum PDFs to English using local Ollama LLMs.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    # Support both kebab-case and camelCase parameters
    group = parser.add_mutually_exclusive_group(required=False)
    group.add_argument(
        "--input-folder",
        "--inputFolder",
        dest="input_folder",
        default=None,
        help="Path to folder containing PDF articles to translate.",
    )
    group.add_argument(
        "--input-file",
        "--inputFile",
        dest="input_file",
        default=None,
        help="Path to a single PDF article file to translate.",
    )

    parser.add_argument(
        "--lang",
        default="de",
        help="ISO 639-1 code for source language of input PDFs (e.g. 'de' for German, 'fr' for French).",
    )
    parser.add_argument(
        "--target-lang",
        default="en",
        help="ISO 639-1 code for target language (default: 'en').",
    )
    parser.add_argument(
        "--model",
        default=DEFAULT_MODEL,
        help=f"Ollama model to use for translation (default: {DEFAULT_MODEL}).",
    )
    parser.add_argument(
        "--ollama-url",
        default=DEFAULT_OLLAMA_URL,
        help=f"Base URL of local Ollama server (default: {DEFAULT_OLLAMA_URL}).",
    )
    parser.add_argument(
        "--output-folder",
        "--outputFolder",
        dest="output_folder",
        default=None,
        help="Custom output folder. If omitted, defaults to an 'en' subfolder inside input directory.",
    )
    parser.add_argument(
        "--browser-path",
        default=None,
        help="Path to Google Chrome or Microsoft Edge executable. Auto-detected if omitted.",
    )
    parser.add_argument(
        "--cookie",
        default=None,
        help="Optional session cookie string to authenticate with forum if downloading protected boards.",
    )
    parser.add_argument(
        "--cookie-file",
        default=None,
        help="Optional path to a file containing session cookie string or Netscape cookies.txt.",
    )
    parser.add_argument(
        "--render-timeout",
        type=int,
        default=None,
        help="Rendering timeout in seconds for headless browser PDF creation (default: adaptive, min 300s).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Force re-translation and overwrite existing English PDFs in 'en' subfolder.",
    )
    parser.add_argument(
        "--save-text",
        action="store_true",
        help="Save plain text translation (.txt) in 'text' subfolder (en/text).",
    )

    args = parser.parse_args(argv)

    # Validate that at least one of input_folder or input_file is given
    if not args.input_folder and not args.input_file:
        parser.error("Either --input-folder or --input-file is required.")

    return args


def main():
    args = parse_arguments()

    # Configure forum session cookie if provided
    if args.cookie:
        philaforum_scraper.COOKIE = parse_cookie_input(args.cookie)
    elif args.cookie_file and os.path.isfile(args.cookie_file):
        try:
            with open(args.cookie_file, "r", encoding="utf-8") as f:
                philaforum_scraper.COOKIE = parse_cookie_input(f.read())
            print(f"Loaded session cookie from {args.cookie_file}")
        except Exception as e:
            print(f"Warning: Could not read cookie file {args.cookie_file}: {e}")

    # Check Ollama status
    if not check_ollama_available(args.ollama_url):
        print(
            f"Error: Could not connect to Ollama at {args.ollama_url}.\n"
            f"Please ensure the Ollama service is running (e.g. run 'ollama serve' or start Ollama app).",
            file=sys.stderr,
        )
        sys.exit(1)

    # Resolve browser executable
    try:
        browser_path = find_browser_executable(args.browser_path)
        print(f"Using browser: {browser_path}")
    except FileNotFoundError as err:
        print(f"Error: {err}", file=sys.stderr)
        sys.exit(1)

    # Determine input files and output directory
    pdf_files: List[str] = []
    if args.input_file:
        if not os.path.isfile(args.input_file):
            print(f"Error: Specified input file does not exist: {args.input_file}", file=sys.stderr)
            sys.exit(1)
        pdf_files = [os.path.abspath(args.input_file)]
        parent_dir = os.path.dirname(os.path.abspath(args.input_file))
        parent_name = os.path.basename(parent_dir).lower()
        has_sibling_images = os.path.isdir(os.path.join(os.path.dirname(parent_dir), "images"))

        if args.output_folder:
            output_dir = args.output_folder
        elif parent_name == args.lang.lower() or has_sibling_images:
            output_dir = os.path.join(os.path.dirname(parent_dir), args.target_lang)
        else:
            output_dir = os.path.join(parent_dir, args.target_lang)
    else:
        if not os.path.isdir(args.input_folder):
            print(f"Error: Specified input folder does not exist: {args.input_folder}", file=sys.stderr)
            sys.exit(1)
        target_input_dir = os.path.abspath(args.input_folder)

        # If input_folder contains a subfolder for source lang (e.g. output_pdfs/Bergedorf/de), use that subfolder
        lang_subfolder = os.path.join(target_input_dir, args.lang)
        if os.path.isdir(lang_subfolder):
            sub_pdfs = [
                os.path.join(lang_subfolder, f)
                for f in sorted(os.listdir(lang_subfolder))
                if f.lower().endswith(".pdf") and not f.startswith(".")
            ]
            if sub_pdfs:
                target_input_dir = lang_subfolder

        folder_name = os.path.basename(target_input_dir).lower()
        has_sibling_images = os.path.isdir(os.path.join(os.path.dirname(target_input_dir), "images"))

        if args.output_folder:
            output_dir = args.output_folder
        elif folder_name == args.lang.lower() or has_sibling_images:
            output_dir = os.path.join(os.path.dirname(target_input_dir), args.target_lang)
        else:
            output_dir = os.path.join(target_input_dir, args.target_lang)

        # Collect all PDF files in target_input_dir (excluding target_lang subfolder)
        for fname in sorted(os.listdir(target_input_dir)):
            if fname.lower().endswith(".pdf") and not fname.startswith("."):
                pdf_files.append(os.path.join(target_input_dir, fname))

    if not pdf_files:
        print(f"No PDF files found to translate in {args.input_folder or args.input_file}.")
        sys.exit(0)

    os.makedirs(output_dir, exist_ok=True)
    print(f"\n========================================================")
    print(f"Starting translation of {len(pdf_files)} PDF(s)...")
    print(f"Source Language: {get_language_name(args.lang)} ({args.lang})")
    print(f"Target Language: {get_language_name(args.target_lang)} ({args.target_lang})")
    print(f"Output Directory: {output_dir}")
    print(f"========================================================")

    start_time = time.time()
    successful = 0

    for idx, pdf_path in enumerate(pdf_files, 1):
        print(f"\n[{idx}/{len(pdf_files)}] Translating: {os.path.basename(pdf_path)}")
        res = translate_single_pdf(
            pdf_path=pdf_path,
            output_dir=output_dir,
            browser_path=browser_path,
            source_lang=args.lang,
            target_lang=args.target_lang,
            model=args.model,
            ollama_url=args.ollama_url,
            force=args.force,
            save_text=args.save_text,
            render_timeout=args.render_timeout,
        )
        if res:
            successful += 1

    elapsed = time.time() - start_time
    print(f"\nFinished! Successfully translated {successful}/{len(pdf_files)} PDF(s) in {elapsed:.1f}s.")
    print(f"Output location: {os.path.abspath(output_dir)}")


if __name__ == "__main__":
    main()
